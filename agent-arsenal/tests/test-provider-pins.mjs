import assert from "node:assert/strict";
import {execFileSync} from "node:child_process";
const script="agent-arsenal/runtime/validate-provider-pins.mjs";
const out=execFileSync(process.execPath,[script],{encoding:"utf8"});
const result=JSON.parse(out);
assert.equal(result.status,"READY");
assert.ok(Array.isArray(result.productionActiveProviders));
assert.ok(result.productionActiveProviders.includes("c6_os"), "C6-Os must be explicitly production-active");
assert.ok(Array.isArray(result.unPinnedProductionProviders));
assert.equal(result.unPinnedProductionProviders.length,0);
console.log("provider pin gate: PASS (only explicitly production-active providers require immutable pins)");
